let currentLang: Language = 'es';
const listeners = new Set<(lang: Language) => void>();

if (typeof window !== 'undefined') {
  const saved = localStorage.getItem('cartoon_kitchen_lang');
  if (saved && saved in TRANSLATIONS) {
    currentLang = saved as Language;
  } else {
    // Detect browser language
    const navLang = navigator.language.split('-')[0] as Language;
    if (navLang in TRANSLATIONS) {
      currentLang = navLang;
    }
  }
}

export function getLanguage(): Language {
  return currentLang;
}

export function setLanguage(lang: Language) {
  if (lang in TRANSLATIONS) {
    currentLang = lang;
    localStorage.setItem('cartoon_kitchen_lang', lang);
    listeners.forEach(cb => cb(lang));
  }
}

export function t(key: string, values?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['es'];
  let text = dict[key];
  if (text === undefined) {
    // fallback to es
    text = TRANSLATIONS['es'][key] || key;
  }
  if (values) {
    Object.entries(values).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

export function useTranslation() {
  const [lang, setLangState] = useState<Language>(currentLang);

  useEffect(() => {
    const handleUpdate = (newLang: Language) => {
      setLangState(newLang);
    };
    listeners.add(handleUpdate);
    return () => {
      listeners.delete(handleUpdate);
    };
  }, []);

  return { lang, t, setLanguage, languages: LANGUAGES };
}
